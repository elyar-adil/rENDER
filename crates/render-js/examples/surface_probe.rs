fn main() {
    let mut dom = parse_document("<!doctype html><html><body></body></html>").dom;
    let mut runtime = JsRuntime::new(&dom);
    let mut missing = Vec::new();
    for name in NAMES {
        let source = format!(
            "(function(){{ try {{ return typeof ({name}); }} catch (e) {{ return 'throws:' + e.message; }} }})()"
        );
        let result = runtime.execute(&mut dom, &source).map_or_else(
            |error| format!("ERR {error}"),
            |outcome| outcome.value.to_js_string(),
        );
        if result == "undefined" || result.starts_with("throws") || result.starts_with("ERR") {
            missing.push(format!("{name} -> {result}"));
        }
    }
    println!("{} of {} missing", missing.len(), NAMES.len());
    for line in missing {
        println!("  {line}");
    }
}
